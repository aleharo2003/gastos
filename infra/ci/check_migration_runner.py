"""Prueba el núcleo del runner remoto solo en la base desechable de CI."""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'cd'))
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import text
from migrate_test import migrate, MigrationError, LOCK_ID
from app.db.connection import create_migration_engine


def check_migration_runner(migration_url):
    engine = create_migration_engine(migration_url)
    try:
        # Antes de migrar la fixture esta vacia; no admite otra base.
        with engine.connect() as c:
            if c.execute(text("SELECT to_regclass('public.alembic_version')")).scalar_one() is not None:
                raise ValueError('La prueba del runner requiere la base temporal sin migrar.')
        with engine.begin() as locked:
            locked.execute(text('SELECT pg_advisory_xact_lock(:key)'), {'key':LOCK_ID})
            try:
                migrate(engine)
            except MigrationError as error:
                if 'Otra migracion' not in str(error):
                    raise
            else:
                raise ValueError('El runner ignoro una migracion concurrente.')
        with engine.begin() as c:
            c.execute(text('CREATE TABLE public.gastos_ci_remote_drift (id integer PRIMARY KEY)'))
        try:
            migrate(engine)
        except AutogenerateDiffsDetected:
            pass
        else:
            raise ValueError('El runner no rechazo drift antes del commit.')
        with engine.begin() as c:
            if c.execute(text("SELECT to_regclass('public.espacios')")).scalar_one() is not None:
                raise ValueError('Las migraciones quedaron aplicadas tras fallar el check.')
            if c.execute(text("SELECT to_regclass('public.alembic_version')")).scalar_one() is not None:
                raise ValueError('Se confirmo la revision pese al fallo.')
            c.execute(text('DROP TABLE public.gastos_ci_remote_drift'))
        first = migrate(engine)
        second = migrate(engine)
        if first != second:
            raise ValueError('El runner no conserva head al repetirse.')
    finally:
        engine.dispose()
    print('OK: runner de migraciones; bloqueo concurrente, rollback ante drift y repeticion sin cambios.', flush=True)
